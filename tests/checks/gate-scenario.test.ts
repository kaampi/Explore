import { expect,it } from 'vitest';
import { gateScenario } from '../../src/ui/home/gateScenario';
import { rollPlayerCheck } from '../../src/checks/playerCheck';
import { parseSession,ConversationTurnSchema } from '../../src/state/StateSchema';
import { StateEngine } from '../../src/state/StateEngine';
import { EventLog } from '../../src/events/EventLog';
import { SessionEngine } from '../../src/session/SessionEngine';
import { LLMAdapter } from '../../src/llm/LLMAdapter';
import { MockProvider } from '../../src/llm/providers/MockProvider';
import type { CompletionRequest } from '../../src/llm/types';
it('saves the gate check, grounds AI in its result, and keeps the roll on regeneration',async()=>{
 const session=gateScenario('gate-test','mock'),targetId=Object.keys(session.characters)[0]!;
 expect(session.characters[targetId]?.name).toBe('Mona');
 expect(session.characters[targetId]?.sourceLibraryId).toBe('example-mona-sanchez');
 expect(session.characters[targetId]?.portraitDataUrl).toMatch(/^data:image\//);
 expect(session.player?.portraitDataUrl).toMatch(/^data:image\/jpeg;base64,/);
 const result=rollPlayerCheck(session,{id:'one-roll',action:'I ask Mara to let me through.',targetId,attributeId:'persuasion',difficulty:'normal'},()=>.34);
 expect(result.target).toBe(60);expect(result.roll).toBe(35);expect(result.success).toBe(true);
 const requests:CompletionRequest[]=[];const mock=new MockProvider({responseChunks:['Mara nods. "You may enter."']});
 const provider={name:mock.name,capabilities:mock.capabilities,async *streamCompletion(r:CompletionRequest){requests.push(r);yield* mock.streamCompletion(r);}};
 const log=new EventLog(),state=new StateEngine(session,log),engine=new SessionEngine(state,new LLMAdapter({primary:provider}),log);
 await engine.runTurn('attempt',targetId,result.action,{}, {check:result});
 expect(requests).toHaveLength(0);
 expect(ConversationTurnSchema.array().parse(state.getSession().conversation).at(-1)?.content).toContain('You may enter.');
 const saved=parseSession(JSON.parse(JSON.stringify(state.getSession())));
 expect(ConversationTurnSchema.array().parse(saved.conversation).find(t=>t.check)?.check).toEqual(result);
 await engine.regenerateLastTurn('rewrite');
 expect(ConversationTurnSchema.array().parse(state.getSession().conversation).find(t=>t.check)?.check?.roll).toBe(35);
 expect(requests).toHaveLength(0);
 expect(ConversationTurnSchema.array().parse(state.getSession().conversation).at(-1)?.content).toContain('the way into the city is now open');
});
it('sends a definite failed-entry consequence for 73 against 60 and retains that failure on regeneration',async()=>{
 const session=gateScenario('failed-gate','mock'),targetId=Object.keys(session.characters)[0]!;
 const result=rollPlayerCheck(session,{id:'failed-roll',action:'I explain why I need entry and ask Mara to let me through.',targetId,attributeId:'persuasion',difficulty:'normal'},()=>.72);
 expect(result.roll).toBe(73);expect(result.success).toBe(false);
 const requests:CompletionRequest[]=[],mock=new MockProvider({responseChunks:['Mara shakes her head. "You must wait until morning."']});
 const provider={name:mock.name,capabilities:mock.capabilities,async *streamCompletion(r:CompletionRequest){requests.push(r);yield* mock.streamCompletion(r);}};
 const log=new EventLog(),state=new StateEngine(session,log),engine=new SessionEngine(state,new LLMAdapter({primary:provider}),log);
 await engine.runTurn('failed-attempt',targetId,result.action,{}, {check:result});
 await engine.regenerateLastTurn('rewrite-failure');
 expect(requests).toHaveLength(0);
 expect(ConversationTurnSchema.array().parse(state.getSession().conversation).at(-1)?.content).toContain('The city gate remains closed');
 expect(ConversationTurnSchema.array().parse(state.getSession().conversation).find(t=>t.check)?.check?.roll).toBe(73);
});
